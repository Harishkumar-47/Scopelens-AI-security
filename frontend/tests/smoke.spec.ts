import { test, expect } from '@playwright/test'

test('dashboard workflow is responsive and interactive', async ({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Build your AI. Define its boundaries.'})).toBeVisible()
  await page.getByRole('button',{name:'WITHOUT',exact:true}).click()
  await expect(page.getByText('No gateway',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'WITH SCOPELENS',exact:true}).click()
  await expect(page.getByText('ALLOW · WARN · ASK · BLOCK')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBeTruthy()
  await page.getByRole('button',{name:/Switch to .* theme/}).click()
  expect(errors).toEqual([])
})

